"""One continuous body's language-action / real-text-response training cycle.

Generated bytes self-hear, select a bounded retrieval-world response, and are
excluded from external CE. A disjoint next segment is scored before and after
learning the response, then is itself consumed and trained. Policy credit uses
the action-time score gradient after one supervised update: this is explicitly
a stale, partial three-factor estimator, not the complete shared-policy
gradient theorem. No historical autograd graph is retained across the update.
"""
from __future__ import annotations

import hashlib
import numpy as np
import torch
import torch.nn.functional as F

from scripts.ib_local.language_action import peek
from scripts.ib_local.latent_navigation_v2 import TransitionRead
from scripts.ib_local.train_gdn_fast_table import FLOOR, LEXICAL


class DecisionGraph:
    """One-token causal action rollout with stable CUDA addresses."""
    def __init__(self, model, capture=True):
        self.model = model
        device = next(model.parameters()).device
        self.capture = capture and device.type == 'cuda'
        self.state = model.initial_state(1, device=device)
        self.ids = torch.zeros(1,1,dtype=torch.long,device=device)
        self.table = torch.full((1,1,256),-5.54517744448,device=device)
        if self.capture:
            stream = torch.cuda.Stream()
            stream.wait_stream(torch.cuda.current_stream())
            with torch.cuda.stream(stream), torch.no_grad():
                for _ in range(3): model.predict(self.ids,self.state,self.table)
            torch.cuda.current_stream().wait_stream(stream)
            self.graph = torch.cuda.CUDAGraph()
            with torch.cuda.graph(self.graph), torch.no_grad():
                self.logits, self.next_state, _ = model.predict(self.ids,self.state,self.table)

    @torch.no_grad()
    def start(self, state):
        self.state.copy_(state)

    @torch.no_grad()
    def step(self, byte, probability):
        self.ids[0,0] = byte
        self.table.copy_(torch.as_tensor(np.log(np.maximum(probability,FLOOR)),device=self.table.device)[None,None])
        if self.capture:
            self.graph.replay()
            logits, state = self.logits, self.next_state
        else:
            logits, state, _ = self.model.predict(self.ids,self.state,self.table)
        self.state.copy_(state)
        return logits[0,0]


class DialogueEngine:
    def __init__(self, model, optimizer, recurrent, table, world, pending, rng,
                 mode='active', utterance_bytes=32, response_bytes=480,
                 holdout_bytes=480, baseline=0., baseline_decay=.95):
        if mode not in ('active', 'random', 'silence'):
            raise ValueError('unknown action policy')
        if min(response_bytes, holdout_bytes) < 1 or utterance_bytes < 1:
            raise ValueError('positive response and utterance budgets required')
        if response_bytes + utterance_bytes > model.max_chunk or holdout_bytes > model.max_chunk:
            raise ValueError('response must fit the bounded recurrent window')
        self.model, self.optimizer, self.recurrent, self.table = model, optimizer, recurrent, table
        self.world, self.pending, self.rng, self.mode = world, int(pending), rng, mode
        self.utterance_bytes, self.response_bytes, self.holdout_bytes = utterance_bytes, response_bytes, holdout_bytes
        self.baseline, self.baseline_decay = float(baseline), float(baseline_decay)
        self.device = next(model.parameters()).device
        self.params = [p for p in model.parameters() if p.requires_grad]
        named = list(model.body.named_parameters())
        lexical = [p for n, p in named if n.removeprefix('base.') in LEXICAL]
        other = [p for n, p in named if n.removeprefix('base.') not in LEXICAL]
        adapter = [p for n,p in model.named_parameters() if not n.startswith('body.')]
        self.groups = (lexical, other, adapter)
        self.decision = DecisionGraph(model)

    def _inputs(self, raw, probs):
        ids = torch.as_tensor(raw[:-1].astype(np.int64), device=self.device)[None]
        targets = torch.as_tensor(raw[1:].astype(np.int64), device=self.device)[None]
        logp = torch.as_tensor(np.log(np.maximum(probs, FLOOR)), device=self.device)[None]
        return ids, targets, logp

    @torch.no_grad()
    def _utter(self):
        if self.mode == 'silence':
            return b'', [], []
        if self.mode == 'random':
            # The world provides baseline strings without looking at the hidden state.
            pos = int(self.rng.integers(0, len(self.world.data)-self.utterance_bytes+1))
            prescribed = self.world.data[pos:pos+self.utterance_bytes]
            # These source-position bytes are self-heard by the model, so they
            # cannot later be labeled previously unexposed probe positions.
            self.world.mark_seen(pos,pos+self.utterance_bytes)
        self.decision.start(self.recurrent)
        byte = self.pending
        probs_list, utterance, log_probs = [], [], []
        for i in range(self.utterance_bytes):
            p = peek(self.table, byte)
            logits = self.decision.step(byte, p)
            logp = logits.log_softmax(-1)
            chosen = int(torch.multinomial(logp.exp(), 1)) if self.mode == 'active' else int(prescribed[i])
            log_probs.append(float(logp[chosen]))
            utterance.append(chosen)
            _, observed_probs, _ = self.table.run_credit(np.array([byte, chosen], np.uint8), max_window=1)
            if not np.array_equal(p, observed_probs[0]):
                raise RuntimeError('self-hearing peek differs from prequential table read')
            probs_list.append(p)
            byte = chosen
        return bytes(utterance), probs_list, log_probs

    def _advance(self, loss, features, diagnostics, next_state, actor=None, advantage=0.):
        self.optimizer.zero_grad(set_to_none=True)
        loss.backward()
        if actor is not None:
            for p, grad in zip(self.params, actor):
                if grad is not None:
                    if p.grad is None: p.grad = -advantage*grad
                    else: p.grad.add_(grad, alpha=-advantage)
        norms = torch.stack([torch.nn.utils.clip_grad_norm_(group, 1., foreach=True) for group in self.groups])
        if not torch.isfinite(loss) or not torch.isfinite(norms).all():
            raise FloatingPointError('nonfinite dialogue update')
        receipt = TransitionRead(None, None, diagnostics['read_slots'], diagnostics['read_weights'])
        self.model.commit_observed(features, receipt)
        self.optimizer.step()
        self.recurrent = next_state.detach()
        return float(norms.norm())

    @torch.no_grad()
    def _age_component_ablation(self, ids, targets, start_state, logp, mask):
        """Remove age-group read components without renormalizing other weights.

        Birth is the oldest contributor to a possibly merged entry; it is not
        proof that all of its current value is that old. Every ablation starts
        from the same recurrent state and frozen table.
        """
        memory = self.model.memory
        base_logits, _, _ = self.model.predict(ids, start_state, logp)
        base_ce = F.cross_entropy(base_logits.flatten(0,1),targets.flatten(),reduction='none')
        base_mean = (base_ce*mask.flatten()).sum()/mask.sum().clamp_min(1)
        original = memory.read
        labels = ('0_4k','4k_64k','64k_256k','256k_plus')
        edges = (0,4096,65536,262144,float('inf'))
        result = {}
        for label,lo,hi in zip(labels,edges[:-1],edges[1:]):
            mass = []
            def filtered(features,encoder):
                read = original(features,encoder)
                event = memory.clock+torch.arange(len(features),device=features.device)
                age = (event[:,None]-memory.birth[read.slots]).clamp_min(0)
                selected = (age>=lo)&(age<hi)
                removed = read.weights*selected
                weights = read.weights*(~selected)
                mass.append(removed.sum(-1))
                value = (weights[...,None]*encoder(memory.successor)[read.slots]).sum(-2)
                long_value = (weights[...,None]*encoder(memory.long_successor)[read.slots]).sum(-2)
                return TransitionRead(value,long_value,read.slots,weights)
            memory.read = filtered
            try:
                logits, _, _ = self.model.predict(ids,start_state,logp)
            finally:
                del memory.read
            ce = F.cross_entropy(logits.flatten(0,1),targets.flatten(),reduction='none')
            masked = mask.flatten()
            result[label] = dict(removed_weight=float((mass[0]*masked).sum()/masked.sum().clamp_min(1)),
                nll_change=float((ce*masked).sum()/masked.sum().clamp_min(1)-base_mean))
        return result

    def step(self, directions, age_ablate=False):
        start_state = self.recurrent.clone()
        start_pending = self.pending
        utterance, action_probs, sampled_logp = self._utter()
        response, heldout, info = self.world.take(utterance, self.response_bytes, self.holdout_bytes)
        last_action = utterance[-1] if utterance else start_pending
        _, response_probs, _ = self.table.run_credit(
            np.concatenate((np.array([last_action], np.uint8), response)), max_window=self.response_bytes)
        raw = np.concatenate((np.array([start_pending], np.uint8), np.frombuffer(utterance, np.uint8), response))
        probs = np.concatenate((np.asarray(action_probs, np.float32).reshape(-1,256), response_probs), 0)
        ids, targets, logp = self._inputs(raw, probs)
        own = len(utterance)
        mask = torch.ones_like(targets, dtype=torch.float32); mask[:,:own] = 0
        component_ablation = self._age_component_ablation(ids, targets, start_state, logp, mask) if age_ablate else None

        # Same initial body/input, before opening the autograd graph. This is a
        # local age-conditioned ablation, not a different trained individual.
        with torch.no_grad():
            gain = self.model.read_gain.clone()
            self.model.read_gain.zero_()
            off, _, _ = self.model.predict(ids, start_state, logp)
            self.model.read_gain.copy_(gain)
            off_ce = F.cross_entropy(off.flatten(0,1), targets.flatten(), reduction='none')

        loss, state_after_response, features, diag = self.model.objective(
            ids, targets, start_state, logp, directions, score_mask=mask)
        logits = diag['logits']
        token_ce = F.cross_entropy(logits.detach().flatten(0,1), targets.flatten(), reduction='none')
        receipt = TransitionRead(None, None, diag['read_slots'], diag['read_weights'])
        oldest_age, recent_age = self.model.memory.ages(receipt, len(features))
        age_labels = ('0_4k','4k_64k','64k_256k','256k_plus')
        edges = (0,4096,65536,262144,float('inf'))
        age_bins = {}
        for label, lo, hi in zip(age_labels,edges[:-1],edges[1:]):
            chosen = (oldest_age >= lo) & (oldest_age < hi) & mask.flatten().bool()
            count = int(chosen.sum())
            age_bins[label] = dict(count=count, nll_on=float(token_ce[chosen].mean()) if count else None,
                                   nll_off=float(off_ce[chosen].mean()) if count else None)

        actor = None
        max_policy_error = None
        if own:
            replay_logp = logits[0,:own].log_softmax(-1).gather(1,targets[0,:own,None]).flatten()
            max_policy_error = float((replay_logp.detach()-torch.tensor(sampled_logp,device=self.device)).abs().max())
            if max_policy_error > 1e-4:
                raise RuntimeError('sampled utterance and causal replay differ')
            if self.mode == 'active':
                # 1/length normalization is a fixed scale for equal-length actions.
                actor = torch.autograd.grad(replay_logp.mean(), self.params, retain_graph=True, allow_unused=True)
                actor = tuple(None if g is None else g.detach().clone() for g in actor)

        # Pre/post use the same heldout bytes and same detached response-end
        # recurrent state. The post branch includes the newly learned memory.
        probe_raw = np.concatenate((response[-1:], heldout))
        _, probe_probs, _ = self.table.run_credit(probe_raw, max_window=self.holdout_bytes)
        probe_ids, probe_targets, probe_logp = self._inputs(probe_raw, probe_probs)
        with torch.no_grad():
            pre_logits, _, _ = self.model.predict(probe_ids, state_after_response.detach(), probe_logp)
            pre = float(F.cross_entropy(pre_logits.flatten(0,1), probe_targets.flatten()))
        response_norm = self._advance(loss, features, diag, state_after_response)
        after_loss, after_state, after_features, after_diag = self.model.objective(
            probe_ids, probe_targets, self.recurrent, probe_logp, directions)
        post = float(after_diag['ce'])
        progress = pre-post
        # A familiar source position supplies zero novelty-conditioned progress.
        # The pre-action baseline must apply to ALL sampled actions, otherwise
        # gating the baseline by an action-dependent outcome adds bias.
        usable_signal = progress if info['holdout_position_fresh'] else 0.
        advantage = usable_signal-self.baseline
        # This actor gradient predates the response update. It is therefore a
        # bounded stale estimator, not exact differentiation through learning.
        heldout_norm = self._advance(after_loss, after_features, after_diag, after_state,
                                     actor=actor, advantage=advantage)
        baseline_before = self.baseline
        self.baseline = self.baseline_decay*self.baseline + (1-self.baseline_decay)*usable_signal
        self.pending = int(heldout[-1])
        try:
            utterance.decode('utf-8'); utf8_valid = True
        except UnicodeDecodeError:
            utf8_valid = False
        return dict(mode=self.mode, utterance_hex=utterance.hex(), utf8_valid=utf8_valid,
            response_sha256=hashlib.sha256(response.tobytes()).hexdigest(),
            heldout_sha256=hashlib.sha256(heldout.tobytes()).hexdigest(),
            external_bytes=len(response)+len(heldout), self_bytes=own, world=info,
            response_nll=float(diag['ce']), heldout_pre_nll=pre, heldout_post_nll=post,
            progress=progress, position_fresh_progress=progress if info['holdout_position_fresh'] else None,
            novelty_conditioned_signal=usable_signal,
            baseline_before=baseline_before, advantage=advantage,
            actor_update_used=actor is not None,
            short_loss=float(diag['latent']), long_loss=float(diag['latent_long']),
            read_age_oldest_mean=float(oldest_age.mean()), read_age_latest_mean=float(recent_age.mean()),
            age_nll=age_bins, age_component_ablation=component_ablation,
            policy_replay_max_error=max_policy_error,
            gradient_norms=[response_norm,heldout_norm], updates=2)
