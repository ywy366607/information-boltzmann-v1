"""Frozen existing RULER cases, carrying trained state and128-byte boundaries.

No new task training. Partial-window generation reexecutes only the uncommitted
prefix of the current128-byte window, so neither S resets nor observed-memory
commits are spuriously performed once per generated byte. No gold is observed
on the free-generation path. Each case branches from its complete checkpoint.
"""
import argparse
import gc
import json
from pathlib import Path
import re
import time

import numpy as np
import torch

from scripts.ib_local import gdn_fused
from scripts.ib_local.language_action import peek
from scripts.ib_local.native_state_policy import apply_native_boundary
from scripts.ib_local.run_causal_water_reply import build
from scripts.ib_local.small_gdn_ruler import encode_case, numeric_scores, request_branch, sha256
from scripts.ib_local.small_gdn_stream_eval import CarriedStream
from scripts.ib_local.train_small_native_credit import continuation_digest
from scripts.ib_local.train_gdn_fast_table import FLOOR


class AnswerStream:
    """Carry completed windows; defer partial-window commits until128 arrivals."""
    def __init__(self, engine, table):
        if getattr(engine.model, 'local_replay', None) is not None:
            raise ValueError('this evaluator targets the original no-native-bank language platform')
        self.engine, self.table = engine, table
        self.reader = CarriedStream(engine, table)
        self.raw = [self.reader.pending]
        self.probabilities = []
        self.cached = None
        self.completed_windows = 0

    @torch.no_grad()
    def observe_prompt(self, prompt):
        if len(self.raw) != 1 or self.probabilities:
            raise ValueError('prompt may only initialize an unused answer stream')
        count = len(prompt)//128*128
        if count:
            self.reader.observe(np.frombuffer(prompt[:count], dtype=np.uint8))
            self.completed_windows += count//128
        self.raw = [self.reader.pending]
        tail = np.frombuffer(prompt[count:], dtype=np.uint8)
        if len(tail):
            _, probs, _ = self.table.run_credit(
                np.concatenate((np.array(self.raw, dtype=np.uint8), tail)), max_window=128)
            self.probabilities = list(probs)
            self.raw.extend(map(int, tail))

    @torch.no_grad()
    def predict_next(self):
        model = self.engine.model
        if hasattr(model.memory, 'begin_read_credit'):
            model.memory.begin_read_credit()
        probabilities = np.stack([*self.probabilities, peek(self.table, self.raw[-1])])
        logp = torch.tensor(np.log(np.maximum(probabilities, FLOOR)),
                            device=self.engine.device)[None]
        ids = torch.tensor([self.raw], device=self.engine.device)
        state = apply_native_boundary(self.engine, self.reader.state)
        self.cached = model.predict_observed(ids, state, logp)
        return self.cached[0][0, -1]

    @torch.no_grad()
    def accept(self, byte):
        if self.cached is None:
            raise RuntimeError('predict before accepting an arrival')
        _, probs, _ = self.table.run_credit(
            np.array([self.raw[-1], byte], dtype=np.uint8), max_window=128)
        self.probabilities.append(probs[0])
        self.raw.append(int(byte))
        if len(self.probabilities) == 128:
            _, state, _, features, receipt = self.cached
            if hasattr(self.engine.model.memory, 'settle_read_credit'):
                self.engine.model.memory.settle_read_credit()
            self.engine.model.commit_observed(features, receipt)
            self.reader.state = state.detach()
            self.reader.pending = int(byte)
            self.raw, self.probabilities = [int(byte)], []
            self.completed_windows += 1
        self.cached = None


@torch.no_grad()
def run_answer(engine, row, cap):
    prefix, gold = encode_case(row)
    # Gold is used only to score the returned text. Never feed it to the body.
    with request_branch(engine, reset_history=False) as table:
        stream = AnswerStream(engine, table)
        stream.observe_prompt(prefix)
        generated = []
        first = None
        for _ in range(cap):
            logits = stream.predict_next()
            byte = int(logits.argmax())
            generated.append(byte)
            if first is None:
                first = byte
            stream.accept(byte)
        text = bytes(generated).decode('utf-8', errors='replace')
        boundary = dict(completed_windows=stream.completed_windows,
                        partial_window_arrivals=len(stream.probabilities))
    metrics = numeric_scores(text, row['outputs'])
    number = re.search(r'\d+', text)
    return dict(index=row['index'], references=row['outputs'], prediction=text,
                prompt_bytes=len(prefix), generation_cap_bytes=cap,
                first_generated_byte=first,
                first_number_first_digit_correct=bool(number and number.group()[0] == row['outputs'][0][0]),
                **boundary, **metrics)


@torch.no_grad()
def boundary_admission(engine, prompt):
    """Actual restored body: last teacher prediction and full commit agree."""
    observed = np.frombuffer(prompt[:128], dtype=np.uint8)
    if len(observed) != 128:
        raise ValueError('128 real prompt bytes required')
    from scripts.ib_local.small_gdn_ruler import fingerprint
    with request_branch(engine, reset_history=False) as table:
        reference = CarriedStream(engine, table).observe(observed)
        expected = fingerprint(engine.model, table)
    with request_branch(engine, reset_history=False) as table:
        stream = AnswerStream(engine, table)
        stream.observe_prompt(bytes(observed[:-1]))
        logits = stream.predict_next()
        error = float((logits.cpu()-reference['logits'][0, -1]).abs().max())
        stream.accept(int(observed[-1]))
        state_error = float((stream.reader.state.cpu()-reference['final_state']).abs().max())
        exact_memory = expected == fingerprint(engine.model, table)
    assert error == 0 and state_error == 0 and exact_memory
    return dict(logits_max_error=error, state_max_error=state_error, memory_exact=exact_memory)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pair', type=Path, required=True)
    parser.add_argument('--manifest', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--limit', type=int, default=8)
    parser.add_argument('--max-new-bytes', type=int, default=32)
    args = parser.parse_args()
    if args.output.exists() or args.limit <= 0 or args.max_new_bytes <= 0:
        raise ValueError('fresh output and positive fixed budgets required')
    torch.set_num_threads(1)
    gdn_fused.enable()
    pair = json.loads(args.pair.read_text())
    manifest = json.loads(args.manifest.read_text())
    datasets = []
    for item in manifest['data']:
        if item['task'] != 'niah_single_1':
            continue
        assert sha256(item['path']) == item['sha256']
        rows = [json.loads(x) for x in Path(item['path']).read_text().splitlines()][:args.limit]
        datasets.append((item, rows))
    report = dict(status='running', protocol=__doc__, optimizer_updates=0,
                  pair_sha256=sha256(args.pair), manifest_sha256=sha256(args.manifest),
                  source_script_sha256=sha256(__file__), official_revision=manifest['official_revision'],
                  max_new_bytes=args.max_new_bytes, arms={}, new_lean_coverage=0)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    started = time.time()
    def write():
        report['seconds'] = time.time()-started
        temp = args.output.with_suffix('.tmp')
        temp.write_text(json.dumps(report, indent=2), encoding='utf-8')
        temp.replace(args.output)
    write()
    try:
        for name, arm in pair['arms'].items():
            engine, _, _, _ = build(Path(arm['checkpoint']))
            assert engine.native_state_policy == arm['policy']
            before = continuation_digest(engine)
            source_hash = sha256(arm['checkpoint'])
            result = dict(checkpoint=arm['checkpoint'], checkpoint_sha256=source_hash,
                          policy=engine.native_state_policy, lengths=[])
            report['arms'][name] = result
            result['boundary_admission'] = boundary_admission(engine, encode_case(datasets[0][1][0])[0])
            assert continuation_digest(engine) == before
            print('ANSWER ADMISSION', name, result['boundary_admission'], flush=True)
            for item, rows in datasets:
                cell = dict(generator_token_budget=item['length'], data_sha256=item['sha256'], samples=[])
                result['lengths'].append(cell)
                for row in rows:
                    case = run_answer(engine, row, args.max_new_bytes)
                    assert continuation_digest(engine) == before
                    cell['samples'].append(case)
                    print('ANSWER', name, item['length'], row['index'],
                          case['first_number_exact'], repr(case['prediction']), flush=True)
                    write()
                cell['counts'] = {k:sum(bool(x[k]) for x in cell['samples']) for k in
                    ('official_contains', 'standalone_number', 'first_number_exact',
                     'first_number_first_digit_correct')}
                cell['count'] = len(rows)
                write()
            result['state_preserved'] = continuation_digest(engine) == before
            result['checkpoint_unchanged'] = sha256(arm['checkpoint']) == source_hash
            assert result['state_preserved'] and result['checkpoint_unchanged']
            del engine
            gc.collect()
            torch.cuda.empty_cache()
        assert sha256(__file__) == report['source_script_sha256']
        report['status'] = 'complete'
    except Exception as exc:
        report.update(status='failed', error=repr(exc))
        raise
    finally:
        write()


if __name__ == '__main__':
    main()
