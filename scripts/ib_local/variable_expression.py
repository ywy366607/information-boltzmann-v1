_proposal_batch = ContextVar('variable_expression_proposal_batch', default=None)


def proposal_batch_for(model):
    active = _proposal_batch.get()
    return active if active is not None and active[0] is model else None


@contextmanager
def proposal_batch_scope(model, batch_size, length):
    """Differentiate B independent proposals from the same pre-action body."""
    if batch_size < 2 or length < 1 or _proposal_batch.get() is not None:
        raise ValueError('proposal batch scope requires batch_size >= 2 and non-nested entry')
    from scripts.ib_local.native_replay_batch import for_model as replay_for
    from scripts.ib_local.native_word_batch import request as endpoint_request
    if replay_for(model) is not None or endpoint_request.get() is not None:
        raise ValueError('proposal batch scope cannot nest with read-only replay or endpoint scopes')
    previous = {}
    for name in ('_question_input_mask', '_question_output_mask'):
        value = getattr(model, name, None)
        if torch.is_tensor(value) and value.ndim == 2 and value.shape == (1, length):
            previous[name] = value
            setattr(model, name, value.expand(batch_size, -1))
    token = _proposal_batch.set((model, batch_size, length))
    try:
        yield
    finally:
        _proposal_batch.reset(token)
        for name, value in previous.items():
            setattr(model, name, value)


@contextmanager
def budget_scope(model, remaining):
    previous=getattr(model,'_expression_remaining',None)
    model._expression_remaining=remaining
    try:yield
    finally:model._expression_remaining=previous


def condition_budget(model, hidden):
    remaining=getattr(model,'_expression_remaining',None)
    if remaining is None or not hasattr(model,'expression_budget_to_hidden'):
        return hidden
    value=torch.as_tensor(remaining,device=hidden.device,dtype=hidden.dtype)
    if value.ndim==0:value=value.expand(*hidden.shape[:-1],1)
    elif value.ndim==2:value=value[...,None]
    return hidden+model.expression_budget_to_hidden(value)


def handover_logits(model, features, remaining):
    remaining=torch.as_tensor(remaining,device=features.device,dtype=features.dtype)
    if remaining.ndim==0:remaining=remaining.expand(*features.shape[:-1],1)
    return model.handover(torch.cat((features,remaining),-1)).squeeze(-1)


def _handover_remaining(decision, remaining):
    """Reuse the budget uploaded for the immediately preceding graph step.

    This is the identical input already used to produce the current feature,
    not a cached prediction or a different stopping policy. Avoid uploading a
    Python scalar to CUDA again for each generated byte.
    """
    if getattr(decision, 'capture', False) and getattr(decision, '_input_host', None) is not None:
        return decision.budget.reshape(())
    return remaining


@contextmanager
def read_route_scope(engine, receipt, start=0, length=None):
    """Differentiate the actually sampled discrete read, with live values.

    Only slot/version identities are retained. Scores, soft weights, contents,
    encodings and their derivatives are recomputed. No later nearest-neighbour
    choice may replace an action-time participant because of GEMM rounding.
    Legacy receipts have no route and retain the strict numerical guard.
    """
    routes = receipt.get('read_slots') if receipt is not None else None
    if routes is None:
        yield
        return
    memory = engine.model.memory
    stop = len(routes) if length is None else start+length
    slots = routes[start:stop]
    versions = receipt['read_versions'][start:stop]
    if (len(slots) != stop-start or slots.ndim != 2 or slots.shape[1] != memory.topk or
            slots.dtype != torch.long or slots.device != memory.source.device):
        raise ValueError('invalid action-time read route')
    if not torch.equal(memory.read_credit_version[slots], versions):
        raise RuntimeError('action-time read route references replaced experience')
    present = '_replay_read_slots' in vars(memory)
    previous = getattr(memory, '_replay_read_slots', None)
    memory._replay_read_slots = slots
    try:
        yield
    finally:
        if present:memory._replay_read_slots = previous
        else:del memory._replay_read_slots


@torch.no_grad()
def film(engine, words, table):
    # ABBA on the actual L32/d256 body: graph replay wins below ~32 bytes;
    # fused sequence execution wins for longer known payloads. This dispatch
    # changes execution layout only, never word content or the update rule.
    if words is not None and len(words) >= 32 and getattr(engine, '_utterance_payload_cache', None) is not None:
        from scripts.ib_local.known_utterance_runtime import known_film
        return known_film(engine, words, table)
    sampled=words is None
    cap=engine.max_utterance
    count=cap if sampled else len(words)
    byte=engine.pending
    engine.decision.start(engine.recurrent)
    p=peek(table,byte)
    said,logps,probs,stops=[],[],[],[]
    stop_ended, stop_tensors, logp_tensors = [], [], []
    routes = []
    has_rc_ver = sampled and hasattr(engine.model.memory, 'read_credit_version')
    def retain_read():
        if has_rc_ver:
            routes.append(engine.decision.read.slots.detach().clone())
    with budget_scope(engine.model,1. if sampled or count else None):
        logits,state=engine.decision.step(byte,p)
        retain_read()
        for i in range(count):
            if sampled and i:
                # The state just self-heard byte i with exactly this remaining
                # budget. A captured head avoids a fresh scalar GPU upload and
                # separate tiny linear call, without moving the sampling/RNG.
                stop=getattr(engine.decision, 'handover_logit', None)
                if stop is None:
                    remaining = _handover_remaining(engine.decision, 1-i/cap)
                    stop=handover_logits(engine.model,state,remaining).reshape(())
                ended=bool(torch.rand((),device=engine.device)<stop.sigmoid())
                stop_tensors.append(stop.detach().clone())
                stop_ended.append(ended)
                if ended:break
            if sampled:
                recalled = getattr(engine, '_draft_recall', ())
                if recalled:
                    from scripts.ib_local.expression_recall import byte_log_probability
                    logp = byte_log_probability(logits, bytes(said), recalled)
                else:
                    logp = logits.log_softmax(-1)
                chosen_t = torch.multinomial(logp.exp(), 1)
                logp_tensors.append(logp[chosen_t.squeeze(0)].detach())
                chosen = int(chosen_t)
            else:chosen=int(words[i])
            said.append(chosen);probs.append(p)
            type(table).run_credit(table,np.array([byte,chosen],np.uint8),max_window=1)
            byte=chosen;p=peek(table,byte)
            engine.model._expression_remaining=1-len(said)/cap
            logits,state=engine.decision.step(byte,p)
            retain_read()
    if stop_tensors:
        stop_vals = torch.stack(stop_tensors).cpu().tolist()
        stops = [dict(logit=float(v), ended=e) for v, e in zip(stop_vals, stop_ended)]
    if logp_tensors:
        logps = [float(v) for v in torch.stack(logp_tensors).cpu().tolist()]
    engine._draft_actions.append(state.detach().clone().reshape(-1))
    engine._last_expression_receipt=dict(stops=stops,final_probability=p,
        reason=('budget' if len(said)==cap else 'handover') if sampled else 'reused_payload',
        length=len(said),cap=cap)
    if routes:
        read_slots = torch.cat(routes)
        engine._last_expression_receipt.update(read_slots=read_slots,
                                               read_versions=engine.model.memory.read_credit_version[read_slots].clone())
    from scripts.ib_local.known_utterance_runtime import remember
    remember(engine, bytes(said), probs, state)
    return bytes(said),logps,probs,0.


@contextmanager
def read_route_scope_batched(engine, receipts, *, target_length=None):
    """Batched action-time read routes for B proposals (causally right-padded)."""
    routes_list = [r.get('read_slots') if r is not None else None for r in receipts]
    if all(r is None for r in routes_list):
        yield
        return
    if any(r is None for r in routes_list):
        raise ValueError('batched read routes require consistent route presence')
    memory = engine.model.memory
    padded_slots, padded_versions = [], []
    for r, slots in zip(receipts, routes_list):
        versions = r['read_versions']
        if target_length is not None and len(slots) < target_length:
            pad = target_length - len(slots)
            slots = torch.cat((slots, slots[-1:].expand(pad, -1)), dim=0)
            versions = torch.cat((versions, versions[-1:].expand(pad, -1)), dim=0)
        padded_slots.append(slots)
        padded_versions.append(versions)
    slots = torch.cat(padded_slots, dim=0)
    versions = torch.cat(padded_versions, dim=0)
    if (slots.ndim != 2 or slots.shape[1] != memory.topk or
            slots.dtype != torch.long or slots.device != memory.source.device):
        raise ValueError('invalid batched action-time read route')
    if not torch.equal(memory.read_credit_version[slots], versions):
        raise RuntimeError('action-time read route references replaced experience')
    present = '_replay_read_slots' in vars(memory)
    previous = getattr(memory, '_replay_read_slots', None)
    memory._replay_read_slots = slots
    try:
        yield
    finally:
        if present:memory._replay_read_slots = previous
        else:del memory._replay_read_slots


def proposal_scores_batched(engine, proposals):
    """One batched forward graph for B handover proposals (causal right-padding).

    Because the recurrent stack is strictly causal and loss only reads positions
    <= len(words_k) for each proposal k, right-padding shorter proposals up to
    max_n preserves exact forward outputs and exact gradients for every proposal.
    Any proposal exceeding the 1e-3 replay guard is returned in fallbacks.
    """
    b = len(proposals)
    if b < 2:
        raise ValueError('proposal_scores_batched requires at least 2 proposals')
    lengths = [len(p['words']) for p in proposals]
    max_n = max(lengths)
    seq_len = max_n + 1
    from scripts.ib_local.adaptive_hamiltonian import bridge_state
    id_rows = []
    prob_rows = []
    receipts = [p['handover'] for p in proposals]
    for p, r, n in zip(proposals, receipts, lengths):
        pad = max_n - n
        id_rows.append([engine.pending, *p['words']] + [0] * pad)
        row_probs = [*p['probs'], r['final_probability']]
        if pad:
            row_probs = row_probs + [r['final_probability']] * pad
        prob_rows.append(row_probs)
    ids = torch.tensor(id_rows, device=engine.device, dtype=torch.long)
    logp = torch.as_tensor(np.log(np.maximum(np.asarray(prob_rows, dtype=np.float32), 1e-6)), device=engine.device)
    remaining = (1 - torch.arange(seq_len, device=engine.device, dtype=logp.dtype)[None] / engine.max_utterance).expand(b, -1)
    start = bridge_state(engine.model, engine.recurrent.detach()).expand(-1, b, -1).contiguous()
    with (proposal_batch_scope(engine.model, b, seq_len),
          budget_scope(engine.model, remaining),
          read_route_scope_batched(engine, receipts, target_length=seq_len)):
        out = engine.model.predict_observed(ids, start, logp)
    hnet = getattr(getattr(engine.model, 'body', None), 'hnet_chunker', None)
    if hnet is not None:
        hnet._pending_ratio_loss = None
    logits_all = out[0]
    h_all = out[3].reshape(b, seq_len, -1)
    valid_terms = {}
    fallbacks = []
    max_error = 0.
    for k, (proposal, receipt, n) in enumerate(zip(proposals, receipts, lengths)):
        byte_terms = logits_all[k, :n].log_softmax(-1).gather(1, ids[k, 1:n+1, None]).flatten()
        error = float((byte_terms.detach() - byte_terms.new_tensor(proposal['logp'])).abs().max()) if n else 0.
        stops = receipt['stops']
        if error <= 1e-3 and stops:
            index = torch.arange(1, len(stops)+1, device=engine.device)
            logits = handover_logits(engine.model, h_all[k, index], remaining[k, index, None])
            expected = logits.new_tensor([s['logit'] for s in stops])
            error = max(error, float((logits.detach() - expected).abs().max()))
            if error <= 1e-3:
                signs = logits.new_tensor([1 if s['ended'] else -1 for s in stops])
                terms = torch.cat((byte_terms, F.logsigmoid(signs * logits)))
        elif error <= 1e-3:
            terms = byte_terms
        if error > 1e-3:
            fallbacks.append(k)
        else:
            valid_terms[k] = terms
            max_error = max(max_error, error)
            engine._batched_replay_hits = getattr(engine, '_batched_replay_hits', 0) + 1
    return valid_terms, fallbacks, max_error


def proposal_score(engine,proposal):
    """One causal fused replay includes the final self-heard state for stopping."""
    words=proposal['words'];n=len(words)
    from scripts.ib_local.adaptive_hamiltonian import bridge_state
    ids=torch.tensor([[engine.pending,*words]],device=engine.device,dtype=torch.long)
    receipt=proposal['handover']
    probs=[*proposal['probs'],receipt['final_probability']]
    logp=torch.as_tensor(np.log(np.maximum(np.stack(probs),1e-6)),device=engine.device)[None]
    remaining=1-torch.arange(n+1,device=engine.device,dtype=logp.dtype)[None]/engine.max_utterance
    with budget_scope(engine.model,remaining), read_route_scope(engine,receipt):
        out=engine.model.predict_observed(ids,bridge_state(engine.model,engine.recurrent.detach()),logp)
    hnet = getattr(getattr(engine.model, 'body', None), 'hnet_chunker', None)
    if hnet is not None:
        hnet._pending_ratio_loss = None
    byte_terms=out[0][0,:n].log_softmax(-1).gather(1,ids[0,1:,None]).flatten()
    error=float((byte_terms.detach()-byte_terms.new_tensor(proposal['logp'])).abs().max())
    # Floating GEMM near a discrete retrieval tie must follow the actual path.
    if error>1e-3:
        # The rejected batched graph is not part of the actual score. Drop
        # both owners before building the exact one-byte graph; otherwise its
        # saved tensors coexist with the fallback's much larger graph.
        del out, byte_terms
        state=bridge_state(engine.model,engine.recurrent.detach());features=[];predictions=[]
        from scripts.ib_local.hnet_chunking import HNetStepState, hnet_step_scope
        step_st = HNetStepState()
        for i in range(n+1):
            with (hnet_step_scope(engine.model, step_st),
                  budget_scope(engine.model,1-i/engine.max_utterance),
                  read_route_scope(engine,receipt,i,1)):
                item=engine.model.predict_observed(ids[:,i:i+1],state,logp[:,i:i+1])
            state=item[1];features.append(item[3]);predictions.append(item[0])
        out=(torch.cat(predictions,1),state,None,torch.cat(features))
        byte_terms=out[0][0,:n].log_softmax(-1).gather(1,ids[0,1:,None]).flatten()
        error=float((byte_terms.detach()-byte_terms.new_tensor(proposal['logp'])).abs().max())
        engine._batched_replay_fallbacks=getattr(engine,'_batched_replay_fallbacks',0)+1
    else:engine._batched_replay_hits=getattr(engine,'_batched_replay_hits',0)+1
    stops=receipt['stops']
    if stops:
        index=torch.arange(1,len(stops)+1,device=engine.device)
        logits=handover_logits(engine.model,out[3][index],remaining[0,index,None])
        expected=logits.new_tensor([s['logit'] for s in stops])
        error=max(error,float((logits.detach()-expected).abs().max()))
        signs=logits.new_tensor([1 if s['ended'] else -1 for s in stops])
        terms=torch.cat((byte_terms,F.logsigmoid(signs*logits)))
    else:terms=byte_terms
    if error>1e-3:raise RuntimeError(f'variable expression replay differs: {error}')
    return terms,error


def release_fallback_cache(engine, previous_count):
    """Release unused allocator blocks after a rare exact-replay fallback.

    Never invoked inside the derivative replay; all actual tensors and the
    captured inference graph remain live. No per-event allocator flushing.
    """
    if (engine.device.type != 'cuda' or
            getattr(engine, '_batched_replay_fallbacks', 0) <= previous_count):
        return None
    before=torch.cuda.memory_reserved()
    torch.cuda.empty_cache()
    return dict(reserved_before_mib=before/2**20,
                reserved_after_mib=torch.cuda.memory_reserved()/2**20)


def configure_variable_expression(engine, *, cap=128, initialize=True):
    if cap!=128:raise ValueError('declared expression budget is 128 bytes')
    model=engine.model
    # The first observed chunk also self-hears up to cap action bytes. The
    # internal-rollout body trains its long head at decision boundaries, so
    # this bounded payload need not fit the old byte-horizon chunk limit.
    from scripts.ib_local.navigation_internal_rollout import InternalRolloutBody
    if isinstance(model, InternalRolloutBody):
        model.max_chunk=max(model.max_chunk, model.memory.long+cap)
        model.memory.max_utterance=cap
    if hasattr(model,'handover'):return
    width=model.encoder.in_features;w=model.encoder.weight
    with torch.random.fork_rng(devices=[w.device] if w.is_cuda else []):
        budget=nn.Linear(1,width,bias=False,device=w.device,dtype=w.dtype)
        head=nn.Linear(width+1,1,device=w.device,dtype=w.dtype)
    nn.init.zeros_(budget.weight)
    # Match the old scale as a birth prior, not a fixed rhythm or length reward.
    nn.init.zeros_(head.weight);nn.init.constant_(head.bias,-math.log(31.))
    model.expression_budget_to_hidden=budget;model.handover=head
    extra=list(budget.parameters())+list(head.parameters())
    engine.optimizer.add_param_group(dict(params=extra,lr=engine.optimizer.param_groups[0]['lr']))
    engine.params=list(model.parameters())
    # Transport pending participation by name order: new heads append zero old
    # participation, rather than acquiring credit for an event before birth.
    if initialize:
        def extend(v):
            if isinstance(v,(tuple,list)) and len(v)==len(engine.params)-len(extra) and all(
                x is None or torch.is_tensor(x) for x in v):
                return type(v)([*v,*([None]*len(extra))])
            if isinstance(v,dict):return {k:extend(x) for k,x in v.items()}
            return v
        engine.prev=extend(engine.prev)
    engine.groups=(*engine.groups,extra)
    engine.variable_expression_schema=1;engine.max_utterance=cap
    # Runtime maximum for retrieval payloads; actual lengths remain per record.
    old=model.retrieval.words
    if old.shape[1]!=cap:
        grown=torch.zeros(old.shape[0],cap,device=old.device,dtype=old.dtype)
        grown[:,:old.shape[1]]=old
        model.retrieval.words=grown
        model.memory.max_utterance=cap
    model._expression_remaining=None
    # Re-capture decoding after adding the budget input and its learned port.
    from scripts.ib_local.scoped_decision_graph import ScopedDecisionGraph
    engine.decision=ScopedDecisionGraph(model,capture=w.is_cuda)
