"""Chemotaxis world, unified interface, multi-state tables (generator M3 with Λ = Fin S).

Same ring world as `cgb_chemotaxis` (same seeds, peaks and cost). The interface is the one every
world now gives an organism, each page derived from an essential:
  page 0 F  receptors (boundary; reservoir potential mu_F = ln c)            -- senses (P3)
  page 1 M  motor (boundary, one unit, mu = 0; state >= 1 = tumble)          -- acts
  page 2 E  store (boundary; mu_E = MU0 + ln(reserve / 150))                 -- metabolism
  page 3 D  waste (boundary; mu_D = -MU0)                                    -- export (G16)
Pages >= 4 are interior, each with 2..4 states. Content of a state is its index. Rules are pair
rules (Lean: `tableCRN` over `Fin S`), simulated exactly by `cgb_table3`. Content drawn from
E costs FUEL per unit (driving costs food).
"""

from __future__ import annotations

import math

import numpy as np
from numba import njit

from cgb_chemotaxis import conc, make_world as _make_world, L, V, C_REF
from cgb_table3 import _run

F, M, E, D = 0, 1, 2, 3
NB = 4
MU0, FUEL = 6.0, 0.0005


def make_world(seed, ticks):
    return _make_world(seed, ticks)


@njit(cache=True)
def _live(counts, phi, bnd, R, kap, Sx, centers, heights, x0, uT, ticks, cost, blind, mode, calm, seed, trace, xs):
    np.random.seed(seed)
    P = counts.shape[0]
    n = np.zeros((P, Sx), dtype=np.int64)
    for p in range(P):
        n[p, 0] = counts[p]
    mu = np.zeros(P)
    fl = np.zeros(P)
    x, direction, reserve = x0, 1.0, 150.0
    mu[F] = 0.0 if blind else math.log(conc(x, centers, heights))
    mu[E], mu[D] = (0.0, 0.0) if calm else (MU0, -MU0)
    _run(n, phi, bnd, mu, R, kap, 20.0, fl)
    tumbles, intake_sum, survival = 0, 0.0, ticks
    for t in range(ticks):
        if mode == 0:
            tumble = n[M, 0] == 0
        elif mode == 1:
            tumble = False
        else:
            tumble = uT[t, 1] < 0.1
        if tumble:
            tumbles += 1
            direction = 1.0 if uT[t, 0] < 0.5 else -1.0
        else:
            x = (x + V * direction) % L
        c = conc(x, centers, heights)
        intake = c / C_REF
        intake_sum += intake
        fuel = max(fl[E], 0.0)
        reserve = min(300.0, reserve + intake) - cost - FUEL * fuel
        if xs.shape[0] > 0:
            xs[t] = x
            trace[t, 0] = 1.0 if tumble else 0.0
            trace[t, 1] = reserve
            for p in range(NB, P):
                occ = 0.0
                for s in range(1, Sx):
                    occ += n[p, s] * s
                trace[t, 2 + p - NB] = occ / max(1, counts[p])
        if reserve <= 0:
            survival = t + 1
            break
        mu[F] = 0.0 if blind else math.log(c)
        mu[E] = 0.0 if calm else MU0 + math.log(max(reserve, 1e-3) / 150.0)
        fl[:] = 0.0
        _run(n, phi, bnd, mu, R, kap, 1.0, fl)
    return survival, intake_sum / survival, tumbles / survival


def arrays(g):
    P = NB + g["interior"]
    S = max(g["states"])
    counts = np.array(g["counts"], dtype=np.int64)
    phi = np.zeros((P, S))
    for p in range(P):
        phi[p, :g["states"][p]] = g["phi"][p]
    bnd = np.zeros(P, dtype=np.bool_)
    bnd[:NB] = True
    R = np.array([[r[0], r[1], -1, r[2], r[3], 0, r[4], r[5], 0] for r in g["rules"]], dtype=np.int64).reshape(-1, 9)
    # rule prefactors are per concentration: the per-pair prefactor is kappa / N (mass action in a
    # well-mixed compartment of N units); the Lean table receives the per-pair value
    N = float(sum(g["counts"]))
    kap = np.array([math.exp(r[6]) / N for r in g["rules"]], dtype=np.float64)
    return counts, phi, bnd, R, kap, S


def live(g, seed, ticks=10000, blind=False, mode=0, calm=False, trace=False, world=None, cost=None, **_):
    w = world if world is not None else make_world(seed, ticks)
    P = NB + g["interior"]
    tr = np.zeros((ticks, 2 + P - NB)) if trace else np.zeros((0, 0))
    xs = np.zeros(ticks) if trace else np.zeros(0)
    out = _live(*arrays(g), w[0], w[1], w[2], w[3], ticks, w[4], blind, mode, calm, seed * 7919 + 3, tr, xs)
    return (out, tr, xs) if trace else out


def to_table(g, name):
    """The genome as a table for the gate and the Lean generator (`cgb_table_medium` format,
    extended with per-page state counts)."""
    P = NB + g["interior"]
    names = ["F", "M", "E", "D"] + [f"I{k}" for k in range(g["interior"])]
    return {
        "name": name,
        "status": "GENERATED by selection over admitted multi-state rule tables in the chemotaxis world",
        "pages": {nm: p for p, nm in enumerate(names)},
        "boundary_pages": list(range(NB)),
        "states": {str(p): int(g["states"][p]) for p in range(P)},
        "units": {nm: int(g["counts"][p]) for p, nm in enumerate(names)},
        "phi": {str(p): [float(v) for v in g["phi"][p]] for p in range(P)},
        "birth": {str(p): 0 for p in range(P)},
        "rules": [{"name": f"r{k}", "i": r[0], "j": r[1], "a": [r[2], r[3]], "b": [r[4], r[5]],
                   "kappa": float(f"{math.exp(r[6]) / sum(g['counts']):.6g}")} for k, r in enumerate(g["rules"])],
        "stimulus": {"calm": 0, "receptor": "ln c(x)", "motor": 0, "store": "MU0 + ln(reserve/150)",
                     "waste": -MU0},
        "tick_time": 1.0,
    }
