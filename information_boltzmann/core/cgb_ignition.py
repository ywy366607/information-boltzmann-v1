"""Delayed-report world for generated rule-table organisms (prereg CGB_GENERATED_IGNITION_PREREG_20261026).

Trials: 10 quiet ticks, a 2-tick stimulus on page S (present with probability 1/2, reservoir
potential a ~ U[1, 3]), a delay D ~ U{10..150}, a 2-tick go cue on page G (potential GO), then a
6-tick report window. Each window tick with the motor unit M in state 1 pays +R if the stimulus
was present and -R if it was absent. Page E is the organism's own store: its reservoir potential
is mu_E = ln(reserve / 10) (a chemical potential), and content drawn through E costs FUEL per
unit. Pages S, G, E, M are boundary; pages >= 4 are interior. By G24 a weak brief stimulus
cannot be held over long delays by equilibrium relaxation; by G23 no bimodal activity exists
without drive. The stochastic kernel is the same compiled `_run` as in `cgb_table_fast`.
"""

from __future__ import annotations

import math

import numpy as np
from numba import njit

from cgb_table_fast import _run

S, G, E, M = 0, 1, 2, 3
NB = 4
ITI, STIM, GO_LEN, WIN = 10, 2, 2, 6
D_MIN, D_MAX, A_MIN, A_MAX = 10, 150, 1.0, 3.0
GO, R, COST, FUEL, R_REF = 4.0, 1.0, 0.02, 0.002, 10.0


@njit(cache=True)
def _live_ig(counts, phi, bnd, ri, rj, a0, a1, b0, b1, kap, muS, muG, window, present, ticks,
             reserve0, cap, blind, calm_fuel, seed, trace):
    np.random.seed(seed)
    P = counts.shape[0]
    n = np.zeros((P, 2), dtype=np.int64)
    for p in range(P):
        n[p, 0] = counts[p]
    mu = np.zeros(P)
    flux = np.zeros(P)
    reserve = reserve0
    mu[E] = 0.0 if calm_fuel else math.log(reserve / R_REF)
    _run(n, phi, bnd, mu, ri, rj, a0, a1, b0, b1, kap, 5.0, flux)
    survival, intake_sum, reports = ticks, 0.0, 0
    fuel = 0.0
    for t in range(ticks):
        report = n[M, 1] > 0
        reports += 1 if report else 0
        intake = 0.0
        if window[t] and report:
            intake = R if present[t] else -R
        intake_sum += intake
        fuel = max(flux[E], 0.0)
        reserve = min(cap, reserve + intake) - COST - FUEL * fuel
        if trace.shape[0] > 0:
            trace[t, 0] = 1.0 if report else 0.0
            trace[t, 1] = fuel
            for p in range(NB, P):
                trace[t, p - NB + 2] = n[p, 1]
        if reserve <= 0:
            survival = t + 1
            break
        mu[S] = 0.0 if blind else muS[t]
        mu[G] = muG[t]
        mu[E] = 0.0 if calm_fuel else math.log(reserve / R_REF)
        mu[M] = 0.0
        flux[:] = 0.0
        _run(n, phi, bnd, mu, ri, rj, a0, a1, b0, b1, kap, 1.0, flux)
    return survival, intake_sum / survival, reports / survival


def make_world(seed, ticks):
    """Per-tick stimulus and go potentials, report windows and trial labels."""
    rng = np.random.default_rng([seed, 13])
    muS, muG = np.zeros(ticks), np.zeros(ticks)
    window, present = np.zeros(ticks, dtype=np.bool_), np.zeros(ticks, dtype=np.bool_)
    trials = []  # (stim onset, amplitude or 0, delay, window start)
    t = 0
    while t < ticks:
        pres = rng.random() < 0.5
        a = float(rng.uniform(A_MIN, A_MAX))
        d = int(rng.integers(D_MIN, D_MAX + 1))
        s0 = t + ITI
        g0 = s0 + STIM + d
        w0 = g0 + 1
        end = g0 + GO_LEN + WIN
        if pres:
            muS[s0:min(s0 + STIM, ticks)] = a
        muG[g0:min(g0 + GO_LEN, ticks)] = GO
        window[w0:min(w0 + WIN, ticks)] = True
        present[t:min(end, ticks)] = pres
        trials.append((s0, a if pres else 0.0, d, w0))
        t = end
    return muS, muG, window, present, np.array(trials)


def arrays(g):
    P = NB + g["interior"]
    counts = np.array(g["counts"], dtype=np.int64)
    phi = np.array(g["phi"], dtype=np.float64).reshape(P, 2)
    bnd = np.zeros(P, dtype=np.bool_)
    bnd[:NB] = True
    r = g["rules"]
    cols = [np.array([x[c] for x in r], dtype=np.int64) for c in range(6)]
    kap = np.array([math.exp(x[6]) for x in r], dtype=np.float64)
    return (counts, phi, bnd, *cols, kap)


def live(g, seed, ticks=20000, blind=False, calm_fuel=False, trace=False, world=None, cost=None, **_):
    """`cost` is ignored: the world fixes it (COST per tick plus FUEL per unit drawn through E)."""
    w = world if world is not None else make_world(seed, ticks)
    tr = np.zeros((ticks, 2 + g["interior"])) if trace else np.zeros((0, 0))
    out = _live_ig(*arrays(g), w[0], w[1], w[2], w[3], ticks, 150.0, 300.0, blind, calm_fuel,
                   seed * 7919 + 5, tr)
    return (out, tr) if trace else out


def to_table(g, name):
    P = NB + g["interior"]
    names = ["S", "G", "E", "M"] + [f"I{k}" for k in range(g["interior"])]
    return {
        "name": name,
        "status": "GENERATED by selection over admitted rule tables in the delayed-report world",
        "pages": {nm: p for p, nm in enumerate(names)},
        "boundary_pages": list(range(NB)),
        "units": {nm: int(g["counts"][p]) for p, nm in enumerate(names)},
        "phi": {str(p): [float(g["phi"][2 * p]), float(g["phi"][2 * p + 1])] for p in range(P)},
        "birth": {str(p): 0 for p in range(P)},
        "rules": [{"name": f"r{k}", "i": x[0], "j": x[1], "a": [x[2], x[3]], "b": [x[4], x[5]],
                   "kappa": float(round(math.exp(x[6]), 6))} for k, x in enumerate(g["rules"])],
        "stimulus": {"calm": 0, "stim": "a in [1, 3]", "go": GO, "fuel": "ln(reserve / 10)", "motor": 0},
        "tick_time": 1.0,
    }
