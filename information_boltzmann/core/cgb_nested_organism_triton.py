"""Exact event-by-event organism dynamics on the GPU, generated from the organism table.

`kernel_source()` writes a Triton kernel from `cgb_nested_organism` (RULES, EXCH, FUEL, GATE): one
lane per organism; within a world leap of length dt each lane runs Gillespie events (rates
recomputed after every event, the same Lean rates as `Organisms.rates`) until its clock passes dt,
for at most K events. Lanes that would need more than K events in a leap are counted in
`overflow` (the run reports it; a run with overflow is not exact). Pools of the organism's cell are
read when the organism arrives and written when it leaves or the leap ends. World events and
organism events alternate leap by leap (operator splitting at dt).
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import torch
import triton

import cgb_nested_organism as NO

GEN = Path(__file__).resolve().parent / "generated"


def _pf(pool, d):
    return f" * _up({pool}, V)" if d > 0 else (f" * _dn({pool}, V)" if d < 0 else "")


def _cols(T=None):
    """[(rate expression, [effect statements])] in the column order of `Organisms.rates`."""
    T = NO.table_of(T)
    cols = []
    gp, gs = T.GATE
    for r, (i, j, a1, a2, b1, b2, df, dw, gated) in enumerate(T.RULES):
        dE = f"(phi{i}_{b1} + phi{j}_{b2} - phi{i}_{a1} - phi{j}_{a2}" + (f" + FE * {df}.0" if df else "") + ")"
        gate = f" * n{gp}_{gs}.to(tl.float32)" if gated else ""
        for (sgn, src, dst) in ((1, (a1, a2), (b1, b2)), (-1, (b1, b2), (a1, a2))):
            eff = [f"n{i}_{src[0]} -= 1", f"n{j}_{src[1]} -= 1", f"n{i}_{dst[0]} += 1", f"n{j}_{dst[1]} += 1"]
            if df:
                eff += [f"fc += {sgn * df}", f"intake += {-sgn * df}"]
            if dw:
                eff.append(f"wc += {sgn * dw}")
            ex = "-" if sgn == 1 else ""
            cols.append((f"kr{r}{gate} * tl.exp({ex}{dE} / 2.0) * n{i}_{src[0]}.to(tl.float32) * "
                         f"n{j}_{src[1]}.to(tl.float32){_pf('fc', sgn * df)}{_pf('wc', sgn * dw)}", eff))
    for x, (p, a, b, food, gated) in enumerate(T.EXCH):
        pool = "fc" if food else "wc"
        gate = f" * n{gp}_{gs}.to(tl.float32)" if gated else ""
        for (s0, s1, sign) in ((a, b, -1.0), (b, a, 1.0)):
            d = s0 - s1
            pf = f"_up({pool}, V)" if d > 0 else f"_dn({pool}, V)"
            eff = [f"n{p}_{s0} -= 1", f"n{p}_{s1} += 1", f"{pool} += {d}"]
            if food:
                eff.append(f"intake += {-d}")
            fe = f" + FE * {a - b}.0" if food else ""
            cols.append((f"kx{x}{gate} * tl.exp({sign} * (phi{p}_{b} - phi{p}_{a}{fe}) / 2.0) * {pf} * "
                         f"n{p}_{s0}.to(tl.float32)", eff))
    M, run = NO.M, T.RUN
    cols.append((f"tl.where(n{M}_{run} > 0, 0.0, 3.0 * kflip)", ["h = (h + 1 + (frac * 3.0).to(tl.int32)) % 4"]))
    i, j, a1, a2, b1, b2 = T.FUEL
    dE = f"(phi{i}_{b1} + phi{j}_{b2} - phi{i}_{a1} - phi{j}_{a2})"
    cols.append((f"tl.where(n{M}_{run} > 0, kmove * tl.exp(-{dE} / 2.0) * n{i}_{a1}.to(tl.float32) * "
                  f"n{j}_{a2}.to(tl.float32), 0.0)",
                  [f"n{i}_{a1} -= 1", f"n{j}_{a2} -= 1", f"n{i}_{b1} += 1", f"n{j}_{b2} += 1", "step = 1"]))
    cols.append((f"tl.where(n{M}_{run} > 0, kmove * tl.exp({dE} / 2.0) * n{i}_{b1}.to(tl.float32) * "
                  f"n{j}_{b2}.to(tl.float32), 0.0)",
                  [f"n{i}_{b1} -= 1", f"n{j}_{b2} -= 1", f"n{i}_{a1} += 1", f"n{j}_{a2} += 1", "step = -1"]))
    return cols


def kernel_source(K, T=None):
    T = NO.table_of(T)
    cols = _cols(T)
    P = len(T.STATES)
    SM = T.SMAX
    nvars = [(p, s) for p in range(P) for s in range(T.STATES[p])]
    L = []
    w = L.append
    w('"""Generated by cgb_nested_organism_triton.kernel_source from the organism table. Do not edit."""')
    w("import triton")
    w("import triton.language as tl")
    w("")
    w("@triton.jit")
    w("def _up(n, V):")
    w("    nf = n.to(tl.float32)")
    w("    return tl.where(n < V, V - nf, 0.0)")
    w("")
    w("@triton.jit")
    w("def _dn(n, V):")
    w("    nf = n.to(tl.float32)")
    w("    return tl.where(n > 0, nf, 0.0)")
    w("")
    w("@triton.jit")
    w("def organism_leap(n_ptr, phi_ptr, kr_ptr, kx_ptr, kflip_ptr, kmove_ptr, x_ptr, y_ptr, h_ptr,")
    w("                  f_ptr, w_ptr, seed_ptr, intake_ptr, moves_ptr, over_ptr, B, G, V, dt, FE,")
    w("                  BLOCK: tl.constexpr):")
    w("    pid = tl.program_id(0)")
    w("    b = pid * BLOCK + tl.arange(0, BLOCK)")
    w("    m = b < B")
    w("    seed = tl.load(seed_ptr)")
    w(f"    SM = {SM}")
    for p, s in nvars:
        w(f"    n{p}_{s} = tl.load(n_ptr + b * {P * SM} + {p * SM + s}, mask=m, other=0)")
        w(f"    phi{p}_{s} = tl.load(phi_ptr + b * {P * SM} + {p * SM + s}, mask=m, other=0.0)")
    for r in range(len(T.RULES)):
        w(f"    kr{r} = tl.load(kr_ptr + b * {len(T.RULES)} + {r}, mask=m, other=0.0)")
    for x in range(len(T.EXCH)):
        w(f"    kx{x} = tl.load(kx_ptr + b * {len(T.EXCH)} + {x}, mask=m, other=0.0)")
    w("    kflip = tl.load(kflip_ptr + b, mask=m, other=0.0)")
    w("    kmove = tl.load(kmove_ptr + b, mask=m, other=0.0)")
    w("    x = tl.load(x_ptr + b, mask=m, other=0)")
    w("    y = tl.load(y_ptr + b, mask=m, other=0)")
    w("    h = tl.load(h_ptr + b, mask=m, other=0)")
    w("    cell = b * G * G + x * G + y")
    w("    fc = tl.load(f_ptr + cell, mask=m, other=0)")
    w("    wc = tl.load(w_ptr + cell, mask=m, other=0)")
    w("    intake = tl.zeros_like(fc)")
    w("    moves = tl.zeros_like(fc)")
    w("    t = tl.zeros([BLOCK], dtype=tl.float32)")
    w("    go = m")
    w("    it = pid * 0")
    # stop as soon as every lane of the block has passed dt (most lanes need few events per leap)
    w(f"    while (tl.max(go.to(tl.int32), axis=0) > 0) & (it < {K}):")
    for c, (expr, _) in enumerate(cols):
        w(f"        r{c} = {expr}")
    w("        tot = " + " + ".join(f"r{c}" for c in range(len(cols))))
    w("        u1 = tl.rand(seed, b * 2 * {K} + 2 * it)".format(K=K))
    w("        u2 = tl.rand(seed, b * 2 * {K} + 2 * it + 1)".format(K=K))
    w("        t += tl.where(tot > 0.0, -tl.log(1.0 - u1) / tl.maximum(tot, 1e-30), 1e30)")
    w("        go = go & (t < dt)")
    w("        target = u2 * tot")
    w("        acc = tl.zeros_like(tot)")
    w("        step = tl.zeros_like(x)")
    for c, (_, eff) in enumerate(cols):
        w(f"        sel = go & (target >= acc) & (target < acc + r{c}) & (r{c} > 0.0)")
        w(f"        frac = (target - acc) / tl.maximum(r{c}, 1e-30)")
        for e in eff:
            var, op, val = e.split(" ", 2)
            if op == "=":
                w(f"        {var} = tl.where(sel, {val}, {var})")
            else:
                sign = "+" if op == "+=" else "-"
                w(f"        {var} = tl.where(sel, {var} {sign} ({val}), {var})")
        w(f"        acc += r{c}")
    w("        moved = step != 0")
    w("        tl.store(f_ptr + cell, fc, mask=m & moved)")
    w("        tl.store(w_ptr + cell, wc, mask=m & moved)")
    w("        dx = tl.where(h == 0, 1, tl.where(h == 2, -1, 0)) * step")
    w("        dy = tl.where(h == 1, 1, tl.where(h == 3, -1, 0)) * step")
    w("        x = (x + dx + G) % G")
    w("        y = (y + dy + G) % G")
    w("        cell = b * G * G + x * G + y")
    w("        fc = tl.where(moved, tl.load(f_ptr + cell, mask=m & moved, other=0), fc)")
    w("        wc = tl.where(moved, tl.load(w_ptr + cell, mask=m & moved, other=0), wc)")
    w("        moves += tl.where(moved, 1, 0)")
    w("        it += 1")
    w("    over = tl.where(go, 1, 0)")
    for p, s in nvars:
        w(f"    tl.store(n_ptr + b * {P * SM} + {p * SM + s}, n{p}_{s}, mask=m)")
    w("    tl.store(x_ptr + b, x, mask=m)")
    w("    tl.store(y_ptr + b, y, mask=m)")
    w("    tl.store(h_ptr + b, h, mask=m)")
    w("    tl.store(f_ptr + cell, fc, mask=m)")
    w("    tl.store(w_ptr + cell, wc, mask=m)")
    w("    tl.store(intake_ptr + b, tl.load(intake_ptr + b, mask=m, other=0) + intake, mask=m)")
    w("    tl.store(moves_ptr + b, tl.load(moves_ptr + b, mask=m, other=0) + moves, mask=m)")
    w("    tl.store(over_ptr + b, tl.load(over_ptr + b, mask=m, other=0) + over, mask=m)")
    w("    if pid == 0:")
    w("        tl.store(seed_ptr, tl.load(seed_ptr) + 1)")
    return "\n".join(L) + "\n"


def rates_source(T=None):
    """A kernel that writes the generated rate columns of the current state (for the gate)."""
    src = kernel_source(1, T)
    head, body = src.split("    while (tl.max(go.to(tl.int32), axis=0) > 0) & (it < 1):\n")
    cols = _cols(T)
    lines = [head.replace("def organism_leap(", "def organism_rates(out_ptr, ")]
    for c, (expr, _) in enumerate(cols):
        lines.append(f"    r{c} = {expr}\n")
        lines.append(f"    tl.store(out_ptr + b * {len(cols)} + {c}, r{c}, mask=m)\n")
    return "".join(lines)


_MODS = {}


def _load(name, src, fn):
    if name not in _MODS:
        GEN.mkdir(exist_ok=True)
        path = GEN / f"{name}.py"
        if not path.exists() or path.read_text(encoding="utf-8") != src:
            path.write_text(src, encoding="utf-8")
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        _MODS[name] = getattr(mod, fn)
    return _MODS[name]


def _suffix(T):
    T = NO.table_of(T)
    return "" if T.name == "legacy" else f"_{T.name}"


def kernel(K=64, T=None):
    return _load(f"organism_leap_K{K}{_suffix(T)}", kernel_source(K, T), "organism_leap")


def rates_kernel(T=None):
    return _load(f"organism_rates{_suffix(T)}", rates_source(T), "organism_rates")


class ExactOrganisms(NO.Organisms):
    """`Organisms` whose leap runs exact Gillespie events on the GPU (int32 state)."""

    BLOCK = 64

    def __init__(self, world, genomes, seed=0, K=64, **kw):
        super().__init__(world, genomes, seed=seed, **kw)
        dev = self.dev
        self.K = K
        self.n32 = self.n.to(torch.int32).contiguous()
        self.n = self.n32
        self.x32 = self.x.to(torch.int32)
        self.y32 = self.y.to(torch.int32)
        self.h32 = self.h.to(torch.int32)
        self.phi_c = self.phi.contiguous()
        self.kr_c = self.kr.contiguous()
        self.kx_c = self.kx.contiguous()
        self.intake32 = torch.zeros(self.B, dtype=torch.int32, device=dev)
        self.moves32 = torch.zeros(self.B, dtype=torch.int32, device=dev)
        self.overflow = torch.zeros(self.B, dtype=torch.int32, device=dev)
        self.oseed = torch.tensor([(seed * 7919 + 101) % 2000000000], dtype=torch.int32, device=dev)
        self.fn = kernel(K, self.T)

    def leap(self):
        grid = (triton.cdiv(self.B, self.BLOCK),)
        self.fn[grid](self.n32, self.phi_c, self.kr_c, self.kx_c, self.kflip, self.kmove, self.x32, self.y32,
                      self.h32, self.W.f, self.W.w, self.oseed, self.intake32, self.moves32, self.overflow,
                      self.B, self.G, self.V, self.dt, self.foodE, BLOCK=self.BLOCK)

    def kernel_rates(self):
        """(B, C) rate columns computed by the generated kernel code."""
        out = torch.empty(self.B, len(_cols(self.T)), dtype=torch.float32, device=self.dev)
        grid = (triton.cdiv(self.B, self.BLOCK),)
        rates_kernel(self.T)[grid](out, self.n32, self.phi_c, self.kr_c, self.kx_c, self.kflip, self.kmove, self.x32,
                             self.y32, self.h32, self.W.f, self.W.w, self.oseed, self.intake32, self.moves32,
                             self.overflow, self.B, self.G, self.V, self.dt, self.foodE, BLOCK=self.BLOCK)
        return out

    def end_tick(self):
        self.tick += 1
        dead = (self.n32[:, NO.S, 1] == 0) & (self.death < 0)
        self.death.copy_(torch.where(dead, self.tick, self.death))
        self.run_time += (self.n32[:, NO.M, self.T.RUN] > 0).to(torch.int64)


def run_exact(tbl, genomes, world_seeds, ticks=5000, device="cuda", K=64, warm=1500, copies=1, **org_kw):
    """Lives of B organisms (rows of genomes) in B worlds, world leap (fused) then exact organism
    events, the whole tick in one CUDA Graph. Returns numpy dict incl. overflow.
    copies > 1 (common random numbers): world_seeds names W = B / copies worlds; lane c * W + w
    lives in world w (the same rain and the same birth place for every copy c)."""
    import numpy as np
    import cgb_nested_world as NW
    import cgb_nested_world_triton as NT
    B = len(world_seeds) * copies
    Wn = len(world_seeds)
    W = NT.FusedWorld(tbl, B=B, device=device, seed=int(world_seeds[0]))
    wea = NW.Weather(tbl, B=Wn, device=device, seed=0)
    wea.rng = np.random.default_rng(list(map(int, world_seeds)))
    wea.X = wea.rng.normal(0.0, wea.s["rate_sigma"], size=Wn)
    tick_mu = (lambda: wea.tick().repeat(copies, 1, 1)) if copies > 1 else wea.tick
    buf, replay = W.captured()
    for _ in range(warm):
        buf.copy_(tick_mu())
        replay()
    O = ExactOrganisms(W, genomes, seed=int(world_seeds[0]) + 1, K=K, **org_kw)
    if copies > 1:
        for t in (O.x32, O.y32, O.h32):
            t.copy_(t[:Wn].repeat(copies))
    nleap = max(1, int(round(1.0 / W.dt)))

    def tick_fn():
        for _ in range(nleap):
            W.leap()
            O.leap()
        O.end_tick()

    state = (W.f, W.w, O.n32, O.x32, O.y32, O.h32, W.seed, O.oseed)
    snap = [t.clone() for t in state]
    s = torch.cuda.Stream()
    s.wait_stream(torch.cuda.current_stream())
    with torch.cuda.stream(s):
        tick_fn()
    torch.cuda.current_stream().wait_stream(s)
    g = torch.cuda.CUDAGraph()
    with torch.cuda.graph(g):
        tick_fn()
    for t, v in zip(state, snap):
        t.copy_(v)
    for t in (O.tick, O.intake32, O.moves32, O.run_time, O.overflow):
        t.zero_()
    O.death.fill_(-1)
    for _ in range(ticks):
        W.mu32.copy_(tick_mu())
        g.replay()
    death = O.death.cpu().numpy()
    surv = np.where(death < 0, ticks, death)
    return dict(survival=surv, intake=O.intake32.cpu().numpy() / np.maximum(1, surv),
                moves=O.moves32.cpu().numpy(), run_frac=O.run_time.cpu().numpy() / ticks,
                overflow=O.overflow.cpu().numpy())
