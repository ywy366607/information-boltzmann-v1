"""Rule-table media (Lean: `CGB.tableCRN`, M3): one table, three uses.

* `LumpedSim`: exact stochastic simulation. Rates depend only on identity pages and
  states, so the unit-level jump process lumps exactly to counts per (page, state):
  the rate of rule k in direction d is kappa * exp(-dE/2) * (ordered pairs of distinct
  units in the source states). dE = change of single-unit energies phi minus the
  reservoir work mu * dc, where dc is the content the event takes in and mu the
  potential (stimulus) of its first boundary participant (`PairCRN.reservoir`).
* `unit_rates`: a unit-by-unit transcription of the Lean definitions (`RuleSpec.apply`,
  `PairCRN.unitE`, `PairCRN.dE`, `PairCRN.medium.rate`) used by the gate to check the
  lumped simulator.
* `lean_source`: the Lean instance generated from the same table, stamped with its hash.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

import numpy as np


def load(path):
    raw = Path(path).read_bytes()
    t = json.loads(raw)
    t["sha256"] = hashlib.sha256(raw).hexdigest()
    return t


def unit_pages(t):
    pages = []
    for name, count in t["units"].items():
        pages += [t["pages"][name]] * count
    return pages


def energy(t, page, l):
    return t["phi"][str(page)][l]


def reservoir(t, i, j, mu):
    if i in t["boundary_pages"]:
        return mu[i]
    if j in t["boundary_pages"]:
        return mu[j]
    return 0.0


def rule_dirs(t):
    for k, r in enumerate(t["rules"]):
        a, b = tuple(r["a"]), tuple(r["b"])
        yield k, False, r, a, b
        yield k, True, r, b, a


def dE(t, i, j, src, dst, mu):
    dc = dst[0] + dst[1] - src[0] - src[1]  # content = state
    return (energy(t, i, dst[0]) + energy(t, j, dst[1]) - energy(t, i, src[0]) - energy(t, j, src[1])
            - reservoir(t, i, j, mu) * dc)


def unit_rates(t, x, mu):
    """Unit-level events of the Lean medium with positive effect: {(k, dir, u, v): rate}."""
    pages = unit_pages(t)
    out = {}
    for k, d, r, src, dst in rule_dirs(t):
        for u in range(len(pages)):
            for v in range(len(pages)):
                if u == v or pages[u] != r["i"] or pages[v] != r["j"]:
                    continue
                if (x[u], x[v]) != src or src == dst:
                    continue
                out[(k, d, u, v)] = r["kappa"] * math.exp(-dE(t, r["i"], r["j"], src, dst, mu) / 2)
    return out


class LumpedSim:
    def __init__(self, t, seed=0):
        self.t = t
        self.pages = sorted(set(unit_pages(t)))
        self.size = {p: unit_pages(t).count(p) for p in self.pages}
        self.n = {p: np.zeros(2, dtype=np.int64) for p in self.pages}
        for p in self.pages:
            self.n[p][t["birth"][str(p)]] = self.size[p]
        self.rng = np.random.default_rng(seed)
        self.dirs = list(rule_dirs(t))

    def pairs(self, i, j, src):
        a = self.n[i][src[0]]
        b = self.n[j][src[1]] - (1 if (i == j and src[0] == src[1]) else 0)
        return max(int(a) * int(b), 0)

    def rates(self, mu):
        out = []
        for k, d, r, src, dst in self.dirs:
            m = self.pairs(r["i"], r["j"], src)
            out.append(0.0 if m == 0 or src == dst else
                       r["kappa"] * math.exp(-dE(self.t, r["i"], r["j"], src, dst, mu) / 2) * m)
        return np.array(out)

    def run(self, mu, duration):
        tleft = duration
        while True:
            w = self.rates(mu)
            tot = w.sum()
            if tot <= 0:
                return
            dt = self.rng.exponential(1.0 / tot)
            if dt > tleft:
                return
            tleft -= dt
            idx = int(self.rng.choice(len(w), p=w / tot))
            k, d, r, src, dst = self.dirs[idx]
            self.n[r["i"]][src[0]] -= 1
            self.n[r["i"]][dst[0]] += 1
            self.n[r["j"]][src[1]] -= 1
            self.n[r["j"]][dst[1]] += 1


def lean_source(t, module):
    """Lean instance of the table, proved by `tableCRN.axioms` with decidable obligations."""
    pages = unit_pages(t)
    n_units, n_rules = len(pages), len(t["rules"])
    page_list = ", ".join(str(p) for p in pages)
    rules = "\n".join(
        f"  | ⟨{k}, _⟩ => ⟨{r['i']}, {r['j']}, ({r['a'][0]}, {r['a'][1]}), ({r['b'][0]}, {r['b'][1]}), "
        f"{r['kappa']}, by norm_num⟩" for k, r in enumerate(t["rules"]))
    phi = "\n".join(f"  | {p}, l => if l = 0 then {v[0]} else {v[1]}" for p, v in t["phi"].items())
    bid = ", ".join(str(p) for p in t["boundary_pages"])
    name = t["name"]
    life = life_witness_source(t, pages)
    return f'''import CGBAxioms.GenerationLifeGate

/-!
# Organism `{name}`: generated from its rule table

Source: `information_boltzmann/organisms/{name}.json`, sha256 {t["sha256"]}.
Generated by `scripts/gen_lean_organism.py`; do not edit by hand.
Status: {t.get("status", "generated")} States are `Fin 2`,
content is the state, the reservoir potential of a boundary page is its stimulus `μ`.
-/

namespace CGB.Organisms.{module}

/-- Identity page of each unit. -/
def page (u : Fin {n_units}) : ℕ := [{page_list}].getD u 0

/-- The rule table. -/
noncomputable def spec : Fin {n_rules} → RuleSpec (Fin 2)
{rules}

noncomputable def φ : ℕ → Fin 2 → ℝ
{phi}
  | _, _ => 0

noncomputable def μ : ℤ → ℝ := fun z => z

def content : Fin 2 → ℕ := fun l => l

def bid : Finset ℕ := {{{bid}}}

/-- The organism as a medium. -/
noncomputable def medium :=
  (tableCRN spec page bid content φ μ (fun _ => (0 : Fin 2)) (0 : ℤ)).medium

/-- **The organism is a model of the CGB axioms** (M3: unique free state, and every
rule between two interior pages conserves content). -/
theorem axioms : medium.Axioms :=
  tableCRN.axioms spec page bid content φ μ (fun _ => (0 : Fin 2)) (0 : ℤ) (by simp [μ])
    ⟨0, rfl, fun l hl => Fin.ext (by simpa [content] using hl)⟩
    (by intro k; fin_cases k <;> simp [spec, bid, content])
{life}
end CGB.Organisms.{module}
'''


def life_witness(t, pages):
    """A rule touching a boundary page that changes content, with two distinct units on its
    pages: the witness for the life-gate lemmas `tableCRN.exposed_of_rule` and
    `tableCRN.metabolizes_of_rule`. None if the table has no such rule."""
    bnd = set(t["boundary_pages"])
    for k, r in enumerate(t["rules"]):
        if r["kappa"] <= 0 or sum(r["a"]) == sum(r["b"]) or not ({r["i"], r["j"]} & bnd):
            continue
        us = [u for u, p in enumerate(pages) if p == r["i"]]
        for u in us:
            vs = [v for v, p in enumerate(pages) if p == r["j"] and v != u]
            if vs:
                return k, u, vs[0]
    return None


def life_witness_source(t, pages):
    w = life_witness(t, pages)
    if w is None:
        return "\n-- No life witness: no rule moves content through a boundary page (life gate fails).\n"
    k, u, v = w
    args = (f"spec page bid content φ μ (fun _ => (0 : Fin 2)) (0 : ℤ) ⟨{k}, by decide⟩\n"
            f"    (by norm_num [spec]) (u := ⟨{u}, by decide⟩) (v := ⟨{v}, by decide⟩) (by decide)\n"
            f"    (by simp [page, spec]) (by simp [page, spec]) (by simp [spec, content])")
    return f'''
/-- **Life gate L-metabolism** (`Lives.metabolizes`): rule {k} on units {u} and {v} changes content. -/
theorem metabolizes : ∃ a s x, 0 < medium.rate a s x ∧ medium.total (medium.act a s x) ≠ medium.total x :=
  tableCRN.metabolizes_of_rule {args} (fun _ => 0)

/-- **Life gate L-sense** (`Lives.exposed`): the same event exchanges content with a boundary
reservoir, so its rate depends on the stimulus. -/
theorem exposed : medium.Exposed :=
  tableCRN.exposed_of_rule {args}
    (by simp [spec, bid]) (0 : ℤ) 1 (by norm_num [μ])
'''


class TableOrganism:
    """A rule-table organism in a tick world: the world reads the motor page; each tick
    the senses set the boundary reservoir potentials, then the medium runs for one tick.

    `blind=True` cuts the food sensor (its reservoir stays at the no-food potential):
    a sensory-cut control.
    """

    def __init__(self, t, seed=0, blind=False):
        self.t, self.sim, self.blind = t, LumpedSim(t, seed), blind
        p, st = t["pages"], t["stimulus"]
        self.mu = {pg: st["calm"] for pg in self.sim.pages}
        self.mu[p["K"]] = st["fuel"]
        self.mu[p["S"]] = st["food_off"]
        self.mu[p["T"]] = st["arrive_off"]
        self.mu[p["M"]] = st["motor_rest"]
        self.sim.run(self.mu, 5 * t["tick_time"])

    def act(self) -> int:
        m = self.sim.n[self.t["pages"]["M"]]
        return int(m[0] == 0)  # cooperative switch: every motor unit bound

    def sense(self, byte, intake: int, travelled: bool):
        p, st = self.t["pages"], self.t["stimulus"]
        self.mu[p["S"]] = st["food_on"] if (intake and not self.blind) else st["food_off"]
        self.mu[p["T"]] = st["arrive_on"] if travelled else st["arrive_off"]
        self.mu[p["M"]] = st["motor_release"] if travelled else st["motor_rest"]
        self.sim.run(self.mu, self.t["tick_time"])

    def phosphorylated(self) -> int:
        return int(self.sim.n[self.t["pages"]["Y"]][1])
